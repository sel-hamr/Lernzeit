interface Meta {
  title: string
  english: string
  group: string
  level: StoryLevel
  summary: string
  drill?: TopicDrill
}

/**
 * One topic. `n` becomes its id (7 → grammar-007) and each exercise's id adds
 * its place (grammar-007-03). Ids must never change: installing the topics
 * again skips the ids it has, and scores are kept by exercise id. Add new
 * exercises at the end of a list.
 *
 * Examples and exercises are lines in the editor's format:
 * "German = English // why". An exercise is one of:
 * - {{dem|den|der}}: choices, the first is right; {{fährst}}: typed
 * - {{den>dem}}: find the mistake (den), whose fix is dem
 * - "~ sentence / other right order": put the words in order
 * - "prompt => answer": write the sentence
 */
function topic(n: number, meta: Meta, rule: string[], examples: string[], exercises: string[]): StarterTopic {
  const id = `grammar-${String(n).padStart(3, '0')}`
  return {
    id,
    ...meta,
    rule: rule.join('\n'),
    examples: examples.map((line) => {
      const { de, en } = parseLine(line)
      return en ? { de, en } : { de }
    }),
    exercises: exercises.map((line, i) => {
      const { de, en, why } = parseLine(line)
      return { id: `${id}-${String(i + 1).padStart(2, '0')}`, text: de, ...(en ? { en } : {}), ...(why ? { why } : {}) }
    }),
  }
}

